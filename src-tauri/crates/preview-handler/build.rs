use std::env;
use std::fs;
use std::path::PathBuf;

/// The size cap lives in `src-tauri/preview.json`, which Quick Look's build and
/// the web viewer read too, so the three previews cannot drift.
fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let path = manifest_dir
        .join("../../preview.json")
        .canonicalize()
        .unwrap_or_else(|e| panic!("src-tauri/preview.json not found ({e})"));
    println!("cargo:rerun-if-changed={}", path.display());

    let json = fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
    let config: serde_json::Value =
        serde_json::from_str(&json).unwrap_or_else(|e| panic!("invalid preview.json: {e}"));
    let max_bytes = config
        .get("maxDocumentBytes")
        .and_then(serde_json::Value::as_u64)
        .filter(|bytes| *bytes > 0)
        .expect("preview.json: maxDocumentBytes must be a positive integer");

    let generated = format!(
        "// Generated by build.rs from src-tauri/preview.json. Do not edit.\n\
         /// Larger files get a notice instead of a render, so Explorer never waits on one.\n\
         pub const MAX_PREVIEW_BYTES: u64 = {max_bytes};\n"
    );
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("set by cargo"));
    let dest = out_dir.join("limits.rs");
    fs::write(&dest, generated)
        .unwrap_or_else(|e| panic!("failed to write {}: {e}", dest.display()));
}
