// Regenerates src-tauri/src/vault/slug_table.rs: every code point github-slugger's
// `slug()` strips, as ranges, so the Rust port produces the anchors the renderer
// does. The package's regex was built from older Unicode data than any current
// runtime ships, so a port on Unicode properties would disagree on thousands of
// code points. Run `node scripts/gen-slug-table.mjs` after upgrading the package.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { regex } from "github-slugger/regex.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const TABLE_PATH = path.join(HERE, "..", "src-tauri", "src", "vault", "slug_table.rs");

const PER_LINE = 5;

export function strippedRanges() {
  const strip = new RegExp(regex.source, "g");
  const ranges = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const ch = String.fromCodePoint(cp);
    const rest = ch.replace(strip, "");
    if (rest === ch) continue;
    // Stripping half of a surrogate pair would leave a broken string, which a
    // per-character table cannot express.
    if (rest !== "") throw new Error(`the regex splits U+${cp.toString(16)}`);
    const last = ranges.at(-1);
    if (last && last[1] === cp - 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return ranges;
}

const hex = (cp) => `0x${cp.toString(16).padStart(4, "0")}`;

export function renderTable(ranges) {
  const rows = [];
  for (let i = 0; i < ranges.length; i += PER_LINE) {
    const row = ranges.slice(i, i + PER_LINE).map(([lo, hi]) => `(${hex(lo)}, ${hex(hi)}),`);
    rows.push(`    ${row.join(" ")}`);
  }
  return `// Generated by scripts/gen-slug-table.mjs from github-slugger's regex.js: the
// code points \`slug()\` strips. Regenerate it whenever that package changes.

#[rustfmt::skip]
pub(super) const STRIPPED: &[(u32, u32)] = &[
${rows.join("\n")}
];
`;
}

export function currentTable() {
  return readFileSync(TABLE_PATH, "utf-8");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(TABLE_PATH, renderTable(strippedRanges()));
}
