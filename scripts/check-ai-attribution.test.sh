#!/usr/bin/env bash
# Tests for scripts/check-ai-attribution.sh and the pre-push hook that runs it,
# against a throwaway repo.
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
unset GIT_AUTHOR_NAME GIT_AUTHOR_EMAIL GIT_COMMITTER_NAME GIT_COMMITTER_EMAIL

fail() {
  echo "FAIL: $1" >&2
  exit 1
}

check() {
  sh "$repo_root/scripts/check-ai-attribution.sh" "$@" 2> "$tmp/err"
}

passes() {
  local name="$1"
  shift
  check "$@" || fail "$name: expected a pass, got: $(cat "$tmp/err")"
}

fails() {
  local name="$1"
  shift
  if check "$@"; then fail "$name: expected a failure"; fi
}

msg() {
  printf '%s\n' "$@" > "$tmp/msg"
}

git init --quiet "$tmp/repo"
cd "$tmp/repo"
git config user.email test@example.com
git config user.name Test
git commit --quiet --allow-empty -m "feat: first"

# message: the text being committed.
msg "fix: a change" "" "Updates CLAUDE.md and the Claude provider's key slot."
passes "a message naming CLAUDE.md" message "$tmp/msg"
msg "fix: a change" "" "Co-authored-by: Claude <noreply@anthropic.com>"
fails "an agent co-author trailer" message "$tmp/msg"
msg "fix: a change" "" "Co-Authored-By: GitHub Copilot <copilot@example.com>"
fails "another agent's trailer" message "$tmp/msg"
msg "fix: a change" "" "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
fails "a generated-with footer" message "$tmp/msg"
msg "fix: a change" "" "_Generated by [Claude Code](https://claude.ai/code/session_1)_"
fails "a generated-by footer" message "$tmp/msg"
msg "fix: a change" "# Co-authored-by: Claude <noreply@anthropic.com>" \
  "# ------------------------ >8 ------------------------" \
  "+Co-authored-by: Claude <noreply@anthropic.com>"
passes "git's comment block and verbose diff" message "$tmp/msg"
grep -q "Co-authored-by" "$tmp/err" && fail "the comment block was reported"

# message: the identity committing it.
msg "fix: a change"
GIT_AUTHOR_NAME=Claude GIT_AUTHOR_EMAIL=noreply@anthropic.com \
  fails "an agent author" message "$tmp/msg"
grep -q "author: Claude <noreply@anthropic.com>" "$tmp/err" || fail "the agent author was not named"
GIT_COMMITTER_NAME=Codex GIT_COMMITTER_EMAIL=codex@example.com \
  fails "an agent committer" message "$tmp/msg"
GIT_AUTHOR_NAME="Claude Monet" GIT_AUTHOR_EMAIL=claude@example.com \
  passes "a person named Claude" message "$tmp/msg"

# commits: every commit in a range.
base=$(git rev-parse HEAD)
git commit --quiet --allow-empty -m "fix: clean"
passes "a clean range" commits "$base..HEAD"
GIT_AUTHOR_NAME=Claude GIT_AUTHOR_EMAIL=noreply@anthropic.com \
  git commit --quiet --allow-empty -m "fix: by an agent"
agent=$(git rev-parse --short HEAD)
fails "an agent-authored commit" commits "$base..HEAD"
grep -q "$agent author" "$tmp/err" || fail "the agent commit was not named"
passes "a range that stops before it" commits "$base..HEAD~1"
git commit --quiet --allow-empty -m "fix: trailer" -m "Co-authored-by: Claude <noreply@anthropic.com>" --no-verify
fails "a commit with a trailer" commits "HEAD~1..HEAD"
fails "a range git cannot resolve" commits "no-such-ref..HEAD"

# text: a PR description.
printf '%s\n' "## Summary" "Edits CLAUDE.md and \`.claude/rules/\`." > "$tmp/body"
passes "a body naming the agent config files" text "$tmp/body"
printf '%s\n' "## Summary" "" "---" "_Generated by [Claude Code](https://claude.ai/code/session_1)_" > "$tmp/body"
fails "a body with a footer" text "$tmp/body"

# pre-push: only the commits the remote lacks, and never a deletion.
git branch --quiet -M main
zero=0000000000000000000000000000000000000000
push() {
  printf '%s %s %s %s\n' refs/heads/main "$1" refs/heads/main "$zero" |
    sh "$repo_root/.husky/pre-push" origin url 2> "$tmp/err"
}
git update-ref refs/remotes/origin/main "$base"
if push "$(git rev-parse HEAD)"; then fail "pre-push let agent commits through"; fi
git update-ref refs/remotes/origin/main HEAD
push "$(git rev-parse HEAD)" || fail "pre-push rechecked commits the remote has: $(cat "$tmp/err")"
push "$zero" || fail "pre-push refused a deletion: $(cat "$tmp/err")"

echo "check-ai-attribution: all tests passed"
